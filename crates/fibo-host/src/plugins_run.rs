/// The first line of the `AGENTS.md` Fibo writes; a file without it is the user's.
pub(super) const MARK: &str =
    "<!-- 由 Fibo 生成，每次启动会更新；要写自己的说明就删掉这一行，Fibo 就不再覆盖 -->";
pub(super) const MARK_EN: &str =
    "<!-- Generated by Fibo and updated on start; delete this line to keep your own notes -->";
