/// Writes `<config>/AGENTS.md`, the note an Agent finds when it opens the config
/// directory, unless the user wrote their own there.
pub fn write_agents_md() {
    let Some(dir) = fibo_core::agent::config_dir() else {
        return;
    };
    if let Err(e) = write_note(&dir) {
        eprintln!("AGENTS.md: {e}");
    }
}

pub(super) fn write_note(dir: &Path) -> io::Result<()> {
    let path = dir.join("AGENTS.md");
    let (mark, body) = match i18n::lang() {
        Lang::Zh => (MARK, AGENTS_MD),
        Lang::En => (MARK_EN, AGENTS_MD_EN),
    };
    let want = format!("{mark}\n{body}");
    match std::fs::read_to_string(&path) {
        Ok(text)
            if text == want
                || !(text.starts_with(MARK)
                    || text.starts_with(MARK_EN)
                    || text.starts_with(MARK_BEFORE)) =>
        {
            return Ok(())
        }
        Err(e) if e.kind() != io::ErrorKind::NotFound => return Err(e),
        _ => {}
    }
    std::fs::create_dir_all(dir)?;
    let temporary = path.with_extension("md.tmp");
    std::fs::write(&temporary, want)?;
    std::fs::rename(temporary, path)
}

/// Runs one declared command as the app or the host would, and shows everything about how
/// it went: `fibo plugins` only says that a file reads, this says the command works.
pub(super) fn try_run(
    id: &str,
    declaration: &str,
    event: Option<String>,
    cwd: Option<String>,
    send: bool,
) -> io::Result<()> {
    use fibo_core::plugin_command::{self, Failed};
    use fibo_core::{decoration, hook, quota};
    let p = plugin::discover(&plugins_dir()?)
        .into_iter()
        .find_map(|f| f.result.ok().filter(|p| p.id == id))
        .ok_or_else(|| io::Error::other(t!("没有装叫 {id} 的插件", id)))?;
    let files = |kind: Kind| kind.files(&p.dir);
    let cwd = match cwd {
        Some(dir) => dir,
        None => std::env::current_dir()?.display().to_string(),
    };
    let (hooks, decorations, sources) = (
        hook::load(files(Kind::Hooks)).0,
        decoration::load(files(Kind::Decorations)).0,
        quota::load(files(Kind::Quota)).0,
    );
    let pane = decoration::Pane {
        cwd: cwd.clone(),
        ..Default::default()
    };
    let spec = if let Some(h) = hooks.iter().find(|h| h.id == declaration) {
        let on = match event {
            Some(name) => serde_json::from_value(serde_json::Value::String(name.clone()))
                .map_err(|_| io::Error::other(t!("没有 {name} 这个事件", name)))?,
            None => *h.on.first().unwrap_or(&hook::Event::Done),
        };
        let payload = hook::Payload {
            event: on,
            session: t!("试跑的会话").into(),
            agent: "Claude Code".into(),
            title: t!("试跑").into(),
            cwd: cwd.clone(),
            space: Some(t!("试跑").into()),
            detail: t!("这是 fibo plugins run 发的样例事件").into(),
            at: fibo_core::content::now(),
            terminal: None,
            exit_code: on
                .is_command()
                .then_some(if on == hook::Event::CommandFailed {
                    1
                } else {
                    0
                }),
            duration_ms: on.is_command().then_some(1200),
        };
        let json = serde_json::to_string(&payload).map_err(io::Error::other)?;
        println!("{}", t!("事件：{json}", json));
        if let (Some(url), false) = (&h.webhook, send) {
            println!(
                "{}",
                t!("会 POST 到 {url}，没有真的发：加 --send 才发", url)
            );
            return Ok(());
        }
        fibo_host::plugin_hooks::command_for(h, &payload).map_err(io::Error::other)?
    } else if let Some(d) = decorations.iter().find(|d| d.id == declaration) {
        d.spec(&pane)
    } else if let Some(s) =
        (sources.iter().filter(|s| s.agent == declaration)).max_by_key(|s| s.command.is_some())
    {
        if s.command.is_none() {
            return Err(io::Error::other(t!(
                "{decl} 的额度来自文件 {file}，没有命令可跑",
                decl = declaration,
                file = s.file.as_deref().unwrap_or_default()
            )));
        }
        s.spec()
    } else {
        let known: Vec<String> = hooks
            .iter()
            .map(|h| h.id.clone())
            .chain(decorations.iter().map(|d| d.id.clone()))
            .chain(sources.iter().map(|s| s.agent.clone()))
            .collect();
        let sep = t!("、");
        return Err(io::Error::other(t!(
            "{id} 没有叫 {decl} 的 hook、装饰或额度命令；有：{known}",
            id,
            decl = declaration,
            known = known.join(sep)
        )));
    };
    println!("{}", t!("PATH：{path}", path = plugin_command::path()));
    let started = std::time::Instant::now();
    let done = plugin_command::run(spec).map_err(|e| {
        io::Error::other(match e {
            Failed::Start(why) => t!("启动不了：{why}", why),
            Failed::TimedOut => {
                t!(
                    "超时，已停止（用了 {ms} ms）",
                    ms = started.elapsed().as_millis()
                )
            }
        })
    })?;
    println!(
        "{}",
        t!(
            "{how}，用了 {ms} ms",
            how = done.how(),
            ms = started.elapsed().as_millis()
        )
    );
    for (name, bytes) in [(t!("输出"), &done.stdout), (t!("错误输出"), &done.stderr)] {
        let text = String::from_utf8_lossy(bytes);
        if !text.trim().is_empty() {
            println!("{}", t!("{name}：\n{text}", name, text = text.trim_end()));
        }
    }
    if done.not_runnable() {
        return Err(io::Error::other(t!(
            "命令跑不起来：在 App 里也一样；检查命令名和上面的 PATH"
        )));
    }
    Ok(())
}
